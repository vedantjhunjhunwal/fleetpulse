"""Requirements traceability check.

REQ: NFR-03 - every requirement in docs/REQUIREMENTS.md must be referenced by at
least one test or check (a "REQ:" comment followed by IDs), and tests may only
reference requirements that exist.

  python tools/trace.py           # check, print a summary
  python tools/trace.py --write   # also regenerate docs/TRACEABILITY.md
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SOURCES = [
    ("decoder/tests", (".c",)),
    ("api/FleetPulse.Api.Tests", (".cs",)),
    ("analytics/tests", (".R",)),
    ("dashboard/src", (".spec.ts",)),
    ("simulator/tests", (".py",)),
    ("tools", (".sh", ".py")),
]
ID = re.compile(r"\b((?:FR|NFR)-\d{2})\b")


def requirements():
    text = open(os.path.join(ROOT, "docs", "REQUIREMENTS.md"), encoding="utf-8").read()
    return {m.group(1): m.group(2).strip() for m in re.finditer(r"^\| ((?:FR|NFR)-\d{2}) \| ([^|]+)\|", text, re.M)}


def references():
    refs = {}
    for folder, exts in SOURCES:
        base = os.path.join(ROOT, folder)
        for dirpath, dirs, files in os.walk(base):
            dirs[:] = [d for d in dirs if d not in ("node_modules", "bin", "obj", "build")]
            for f in files:
                if not f.endswith(exts):
                    continue
                path = os.path.join(dirpath, f)
                for n, line in enumerate(open(path, encoding="utf-8", errors="ignore"), 1):
                    if "REQ:" not in line:
                        continue
                    for rid in ID.findall(line.split("REQ:", 1)[1]):
                        refs.setdefault(rid, []).append(f"{os.path.relpath(path, ROOT)}:{n}")
    return refs


def main():
    reqs, refs = requirements(), references()
    missing = [r for r in reqs if r not in refs]
    unknown = sorted(set(refs) - set(reqs))
    for r in reqs:
        print(f"{r:7} {len(refs.get(r, [])):3} test(s)  {reqs[r][:70]}")
    if "--write" in sys.argv:
        lines = ["# Traceability matrix", "", "Generated by `python tools/trace.py --write`.", "",
                 "| Requirement | Tests |", "|---|---|"]
        for r in reqs:
            files = sorted({x.rsplit(":", 1)[0] for x in refs.get(r, [])})
            lines.append(f"| {r} | {len(refs.get(r, []))} in " + ", ".join(f"`{f}`" for f in files) + " |")
        with open(os.path.join(ROOT, "docs", "TRACEABILITY.md"), "w", encoding="utf-8") as fh:
            fh.write("\n".join(lines) + "\n")
    if missing or unknown:
        print(f"FAIL: untested {missing}, unknown references {unknown}")
        return 1
    print(f"PASS: {len(reqs)} requirements, {sum(len(v) for v in refs.values())} references")
    return 0


if __name__ == "__main__":
    sys.exit(main())
